#!/usr/bin/env python3
"""Build an offline macOS application without installing it."""
from pathlib import Path
import argparse
import json
import plistlib
import re
import shutil
import subprocess

PROJECT = Path(__file__).resolve().parent.parent
WEB = PROJECT / 'src' / 'web'
MAC = PROJECT / 'src' / 'mac'
MARKER = '.quietread-build'


def document_id(rows):
    text = '\n'.join(row['text'] + '\0' + row['section'] for row in rows)
    units = text.encode('utf-16-le')
    value = 2166136261
    for i in range(0, len(units), 2):
        value = ((value ^ (units[i] | units[i + 1] << 8)) * 16777619) & 0xffffffff
    return f'{len(units) // 2}-{value:x}'


def example_script():
    rows = [
        {'text': 'Welcome to QuietRead. Import a text file or paste your own script in Settings.', 'section': 'Getting started'},
        {'text': 'Choose a comfortable speed, then press Start to begin scrolling.', 'section': 'Getting started'},
        {'text': 'Your progress is saved locally so you can return later.', 'section': 'Getting started'},
    ]
    return {'id': document_id(rows), 'title': 'Welcome to QuietRead', 'format': 'Example', 'warnings': [], 'rows': rows}


def create_html():
    html = (WEB / 'template.html').read_text(encoding='utf-8')
    replacements = {
        '__STYLE__': (WEB / 'style.css').read_text(encoding='utf-8'),
        '__BUILTINS__': json.dumps([example_script()], ensure_ascii=False).replace('<', '\\u003c'),
        '__I18N__': (WEB / 'i18n.js').read_text(encoding='utf-8'),
        '__MARKED__': '/*\n' + (WEB / 'vendor' / 'MARKED-LICENSE.md').read_text(encoding='utf-8') + '\n*/\n' + (WEB / 'vendor' / 'marked.umd.js').read_text(encoding='utf-8'),
        '__ENGINE__': (WEB / 'engine.js').read_text(encoding='utf-8'),
        '__STORAGE__': (WEB / 'storage.js').read_text(encoding='utf-8'),
        '__APPLICATION__': (WEB / 'app.js').read_text(encoding='utf-8'),
    }
    for key, value in replacements.items():
        if html.count(key) != 1:
            raise ValueError(f'Expected exactly one {key} placeholder')
        html = html.replace(key, value, 1)
    return html


def create_icon(destination, scratch):
    iconset = scratch / 'AppIcon.iconset'
    iconset.mkdir()
    source = PROJECT / 'assets' / 'icon.png'
    for base in (16, 32, 128, 256, 512):
        for scale in (1, 2):
            name = f'icon_{base}x{base}' + ('@2x' if scale == 2 else '') + '.png'
            subprocess.run(['/usr/bin/sips', '-z', str(base * scale), str(base * scale), str(source), '--out', str(iconset / name)], check=True, stdout=subprocess.DEVNULL)
    subprocess.run(['/usr/bin/iconutil', '-c', 'icns', str(iconset), '-o', str(destination)], check=True)


def build(args):
    output = Path(args.output).expanduser().resolve()
    if output == PROJECT or PROJECT in output.parents and output.name != 'build':
        raise ValueError('Output inside the project must be the build directory')
    if output.exists():
        if not (output / MARKER).is_file():
            raise ValueError('Refusing to replace an output directory without the build marker')
        shutil.rmtree(output)
    output.mkdir(parents=True)
    (output / MARKER).write_text('Generated by QuietRead.\n', encoding='utf-8')
    app = output / (args.name + '.app')
    contents = app / 'Contents'
    (contents / 'MacOS').mkdir(parents=True)
    (contents / 'Resources').mkdir()
    html = create_html()
    (contents / 'Resources/index.html').write_text(html, encoding='utf-8')
    shutil.copyfile(WEB / 'vendor' / 'MARKED-LICENSE.md', contents / 'Resources' / 'MARKED-LICENSE.txt')
    (output / 'QuietRead.html').write_text(html, encoding='utf-8')
    create_icon(contents / 'Resources/AppIcon.icns', output)
    info = {
        'CFBundleName': args.name, 'CFBundleDisplayName': args.name,
        'CFBundleIdentifier': args.bundle_id, 'CFBundleVersion': '3.6',
        'CFBundleShortVersionString': '3.6', 'CFBundleExecutable': 'QuietRead',
        'CFBundlePackageType': 'APPL', 'CFBundleIconFile': 'AppIcon',
        'LSMinimumSystemVersion': '15.0', 'NSHighResolutionCapable': True,
        'CFBundleDevelopmentRegion': 'en', 'QuietReadStorageDirectory': args.storage_dir,
        'QuietReadLegacyStorageLayout': args.legacy_storage_layout,
    }
    with (contents / 'Info.plist').open('wb') as f:
        plistlib.dump(info, f)
    subprocess.run(['xcrun', 'swiftc', '-target', 'arm64-apple-macos15.0', str(MAC / 'Store.swift'), str(MAC / 'App.swift'),
                    '-o', str(contents / 'MacOS/QuietRead'), '-framework', 'Cocoa', '-framework', 'WebKit', '-O'], check=True)
    subprocess.run(['/usr/bin/codesign', '--force', '--sign', '-', str(app)], check=True)
    subprocess.run(['/usr/bin/codesign', '--verify', '--deep', '--strict', str(app)], check=True)
    print(f'Built {app}')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', default=str(PROJECT / 'build'), help='Generated build directory')
    parser.add_argument('--name', default='QuietRead', help='Application name')
    parser.add_argument('--bundle-id', default='org.example.quietread', help='Application bundle identifier')
    parser.add_argument('--storage-dir', default='QuietRead/Data', help='Relative to Application Support')
    parser.add_argument('--legacy-storage-layout', action='store_true', help='Use the previous local data layout')
    args = parser.parse_args()
    if not re.fullmatch(r'[A-Za-z0-9.-]+', args.bundle_id) or not args.name or '/' in args.name or args.name in ('.', '..'):
        parser.error('Invalid application name or bundle identifier')
    if args.storage_dir.startswith('/') or any(part in ('', '.', '..') for part in args.storage_dir.split('/')):
        parser.error('Storage directory must be a safe relative path')
    build(args)


if __name__ == '__main__':
    main()
